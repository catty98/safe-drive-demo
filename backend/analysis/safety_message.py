def create_safety_message(accident_type: str | None) -> str:
    if not accident_type:
        return "분석 가능한 사고 데이터가 부족합니다."

    normalized = str(accident_type).strip()
    detail_message = DETAIL_SAFETY_MESSAGES.get(normalized)

    if detail_message:
        return detail_message

    major_type = normalized.split("_", 1)[0]

    return MAJOR_SAFETY_MESSAGES.get(
        major_type,
        (
            "해당 지역의 교통 흐름과 주변 차량을 확인하고 "
            "제한속도를 준수하세요."
        ),
    )


def create_road_safety_message(road_type: str | None) -> str:
    normalized = str(road_type or "").strip()
    return ROAD_SAFETY_MESSAGES.get(
        normalized,
        "전방 상황을 확인하고 도로의 제한속도와 차로 표시를 준수하세요.",
    )


def create_condition_safety_message(
    weather: str | None,
    time_band: str | None,
) -> str:
    time_text = str(time_band or "").strip()

    if time_text in {"0시~2시", "2시~4시", "4시~6시", "22시~24시"}:
        time_advice = (
            "야간에는 시야가 제한되고 졸음이 발생할 수 있으므로 "
            "차로를 유지하고 피로하면 즉시 휴식하세요."
        )
    elif time_text in {"6시~8시", "8시~10시", "16시~18시", "18시~20시"}:
        time_advice = (
            "통행량이 늘어나는 시간대이므로 교차로·합류부에서 "
            "앞차의 제동과 보행자 진입을 주의하세요."
        )
    else:
        time_advice = (
            "전방 교통 흐름을 확인하고 급가속과 급제동을 피하세요."
        )

    weather_advice = WEATHER_SAFETY_MESSAGES.get(
        str(weather or "").strip(),
        "현재 노면과 시야 상태에 맞춰 속도와 차간 거리를 조절하세요.",
    )

    return f"{time_advice} {weather_advice}"
